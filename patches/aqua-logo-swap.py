def patch_one(path):
    s = io.open(path, encoding="utf-8").read()
    changed = 0
    # ---- ① FISH_PATH 字符串 ----
    m = re.search(r'const FISH_PATH = "([^"]+)"', s)
    if not m:
        return "SKIP(无 FISH_PATH)"
    old = m.group(1)
    if old.startswith(OLD_PREFIX):
        s = s.replace(m.group(0), 'const FISH_PATH = "' + NEW_FISH + '"', 1)
        changed += 1
    elif not old.startswith(FISH_DONE):
        return "SKIP(FISH_PATH 形态未知: %s...)" % old[:24]
    # ---- ② WHALE_SVG 内的 path d ----
    i = s.find("const WHALE_SVG")
    if i == -1:
        return "SKIP(无 WHALE_SVG)"
    j = s.find('<path d="', i)
    k = s.find('"', j + 9) if j != -1 else -1
    if j == -1 or k == -1:
        return "SKIP(WHALE_SVG 结构异常)"
    d = s[j + 9:k]
    if d.startswith(OLD_PREFIX):
        s = s[: j + 9] + NEW_WHALE + s[k:]
        changed += 1
    elif not d.startswith(WHALE_DONE):
        return "SKIP(WHALE d 形态未知: %s...)" % d[:24]
    if changed == 0:
        return "skip(已打)"
    io.open(path, "w", encoding="utf-8", newline="").write(s)
    return "ok(%d处)" % changed


def main():
    args = sys.argv[1:]
    if not args:
        print(__doc__)
        return 1
    if args[0] == "--scan":
        files = sorted(glob.glob(os.path.join(args[1], "**", "dsh-client-ui-aqua", "lib", "client.js"), recursive=True))
    else:
        files = args
    if not files:
        print("没有找到目标文件")
        return 1
    for f in files:
        print(patch_one(f), f)
    return 0


if __name__ == "__main__":
    sys.exit(main())
